-- Native REAPER tests, using real MIDI takes and raw note-off velocities.
local root = assert(REASKII_ROOT)
local output = assert(REASKII_RESULT)
local f = assert(io.open(output, 'w'))
local count = 0
local function check(condition, name)
  assert(condition, name)
  count = count + 1
  f:write('PASS\t' .. name .. '\n'); f:flush()
end
local ok, err = xpcall(function()
  local C = dofile(root .. '/scripts/midi/ReaSkii_MIDI_Core.lua')
  local function event(delta, flags, message)
    return string.pack('i4Bs4', delta, flags, message)
  end
  local input = event(0, 1, string.char(0x90,60,100))
    .. event(120, 0, string.char(0x80,60,37))
    .. event(0, 0, '')
  local changed = C.transform(input, 'transpose', {amount=2})
  local events = C.decode(changed)
  check(events[1].msg:byte(2)==62 and events[2].msg:byte(2)==62, 'transpose note-on and note-off')
  check(events[2].msg:byte(3)==37, 'preserve release velocity')
  check(C.transform(input, 'transpose', {amount=0})==input, 'identity is byte-exact')
  local up = C.transform(input, 'velocity', {amount=10})
  check(C.decode(up)[1].msg:byte(3)==110, 'velocity delta')
  check(C.decode(up)[2].msg:byte(3)==37, 'velocity does not change release velocity')
  local unselected = event(0,0,string.char(0x90,72,80)) .. event(120,0,string.char(0x80,72,22))
  check(C.transform(unselected, 'transpose', {amount=12})==unselected, 'unselected notes untouched')
  check(not pcall(C.transform,input,'transpose',{amount=100}), 'out-of-range pitch refused, not clipped')
  local expression = event(0,0,string.char(0xE0,0,64)) .. input
  check(not pcall(C.transform,expression,'strum',{low=0,high=100,grid=120}), 'timing transform refuses expression data')
  local chord = event(0,1,string.char(0x90,60,100)) .. event(0,1,string.char(0x90,64,100))
    .. event(0,1,string.char(0x90,67,100)) .. event(480,0,string.char(0x80,60,12))
    .. event(0,0,string.char(0x80,64,23)) .. event(0,0,string.char(0x80,67,34)) .. event(0,0,'')
  local strum=C.decode(C.transform(chord,'strum',{low=0,high=100,grid=120}))
  check(strum[1].pos==0 and strum[2].pos==60 and strum[3].pos==120, 'linear strum spans one grid step')
  check(strum[4].pos==480 and strum[6].pos==480, 'strum keeps note ends')
  check(C.transform(chord,'strum',{low=0,high=0,grid=120})==chord, 'strum identity')
  local random1=C.transform(chord,'random_velocity',{amount=20,seed=123})
  check(random1==C.transform(chord,'random_velocity',{amount=20,seed=123}), 'random velocity is reproducible')
  check(random1~=C.transform(chord,'random_velocity',{amount=20,seed=124}), 'random seed affects result')
  check(input==event(0,1,string.char(0x90,60,100)) .. event(120,0,string.char(0x80,60,37)) .. event(0,0,''), 'source snapshot immutable')
  reaper.InsertTrackAtIndex(0,true)
  local track=reaper.GetTrack(0,0)
  local item=reaper.CreateNewMIDIItemInProj(track,0,4,false)
  local take=reaper.GetActiveTake(item)
  assert(reaper.MIDI_SetAllEvts(take,input))
  local _, snapshot = reaper.MIDI_GetAllEvts(take,'')
  reaper.Undo_OnStateChange2(0,'Native MIDI fixture')
  local session = C.session(take)
  session:preview('transpose',{amount=2})
  local _,_,_,_,_,_,p=reaper.MIDI_GetNote(take,0)
  check(p==62,'preview writes native take')
  session:preview('transpose',{amount=3})
  local _,_,_,_,_,_,p2=reaper.MIDI_GetNote(take,0)
  check(p2==63,'preview recalculates from original, not previous preview')
  session:cancel()
  local _, restored=reaper.MIDI_GetAllEvts(take,'')
  check(restored==snapshot,'cancel restores byte-exact MIDI')
  local committed=C.session(take)
  committed:preview('velocity',{amount=5})
  committed:apply('ReaSkii test velocity')
  check(reaper.Undo_CanUndo2(0)=='ReaSkii test velocity','apply creates named undo step')
  reaper.Undo_DoUndo2(0)
  local _, undone=reaper.MIDI_GetAllEvts(take,'')
  check(undone==snapshot,'undo restores original MIDI')
  local conflict=C.session(take)
  conflict:preview('velocity',{amount=5})
  reaper.MIDI_InsertCC(take,false,false,50,0xB0,0,1,90)
  local _,external=reaper.MIDI_GetAllEvts(take,'')
  check(not pcall(function() conflict:cancel() end),'external MIDI edit detected')
  local _,after=reaper.MIDI_GetAllEvts(take,'')
  check(after==external,'conflict never overwrites external edit')
end, debug.traceback)
if not ok then f:write('ERROR\t'..err..'\n') end
f:write('DONE\t'..count..'\n'); f:close()
